/* =====================================================================
   power.h   电源管理：深度休眠 + 水感唤醒
   ---------------------------------------------------------------------
   文档指标：休眠电流 ≤200µA、待机 ≥3 个月。

   机制：
     平时     芯片深睡（5µA 级），水感电极挂着"低电平唤醒"
     入水     水把电极拉低 → 芯片被叫醒
     醒来     芯片重启，setup() 重跑 → 跑正常的水感确认
     确认入水 进入上报模式，一直发
     离水超时 回去睡

   注意：C3 没有 RTC IO，不能用 ext0/ext1；它用
   esp_deep_sleep_enable_gpio_wakeup()，**只有 GPIO0~5 能唤醒**。
   水感电极正好在 GPIO3/4。
   ===================================================================== */

#ifndef CB_POWER_H
#define CB_POWER_H

#include "config.h"
#include "debug.h"

void powerBegin();            // setup 里最早调：解除上次休眠留下的引脚保持
bool powerWokeByWater();      // 这次是不是被水感电极叫醒的

void powerGpsOn();            // 给北斗上电（没接开关就是空操作）
void powerGpsOff();           // 给北斗断电

void powerGoSleep();          // 睡下去 —— **不返回**

#endif
