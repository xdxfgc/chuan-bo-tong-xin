#pragma once
/* ============================================================
 *  button.h —— 板载按键模块（对外接口）
 *
 *  这一层只负责"按键被怎么按了"，不负责"按了该干什么"：
 *  短按/长按它都翻译成一条控制台命令（key short / key long）交给
 *  console 去执行，于是按键、串口、网页三条路走的是同一段逻辑。
 * ============================================================ */
#include <Arduino.h>

void buttonBegin();     // setup() 里调一次：配置引脚、读初始电平
void buttonUpdate();    // loop() 里每次都调：消抖、判长短按（非阻塞）
bool buttonPressed();   // 此刻是否按着（给诊断用）
